    private Persona instanciarPersona(){
        try{
            String curp = txtCURP.getText();
            String nombres = txtNombres.getText();
            String apellidos = txtApellidos.getText();
            int edad = Integer.parseInt(txtEdad.getText());
            String rol = txtRol.getText();
            
            return new Persona(curp, nombres, apellidos, edad, rol);
        } catch (NumberFormatException ex){
            JOptionPane.showMessageDialog(this, "La edad debe ser un número entero válido.", "Error",JOptionPane.ERROR_MESSAGE);
            return null;
        } catch (IllegalArgumentException ex){
            JOptionPane.showMessageDialog(this, ex.getMessage() ,"Error de Validación", JOptionPane.ERROR_MESSAGE);
            return null;
        }
    }
    
    private void actualizarVista(){
        String datos = lista.mostrarElementos();
        if (datos == null || datos.trim().isEmpty()){
            txtAreaVisualizacion.setText("La lista está vacía.");
        } else {
            txtAreaVisualizacion.setText(datos);
        }
        
        txtCURP.setText("");
        txtNombres.setText("");
        txtApellidos.setText("");
        txtEdad.setText("");
        txtRol.setText("");
    }
